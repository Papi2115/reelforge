export interface Glyph {
  readonly w: number;
  readonly h: number;
  readonly bits: Uint8Array;
}

export interface Font {
  readonly glyphs: ReadonlyMap<string, Glyph>;
  readonly alternates: ReadonlyMap<string, Glyph>;
  /** Width of a space in cells. */
  readonly space: number;
  /** Gap between glyphs in cells. */
  readonly spacing: number;
}

function compile(map: Readonly<Record<string, string>>): Map<string, Glyph> {
  const out = new Map<string, Glyph>();
  for (const [char, rows] of Object.entries(map)) {
    const lines = rows.split('/');
    const w = lines[0]?.length ?? 0;
    const bits = new Uint8Array(w * lines.length);
    lines.forEach((line, y) => {
      for (let x = 0; x < w; x += 1) bits[y * w + x] = line[x] === '#' ? 1 : 0;
    });
    out.set(char, { w, h: lines.length, bits });
  }
  return out;
}

