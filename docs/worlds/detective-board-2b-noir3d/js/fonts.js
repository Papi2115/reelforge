  /**
   * Lay out text into strokes in card millimetres (y down, origin = top-left of the cap line).
   * opts: {font:'type'|'disp'|'hand', size: cap height mm, x, y, seed, slant, track, t0, cps, align}
   * Returns {strokes:[{p:[...], ts, te}], w}. ts/te are global write-on times (te < ts never; static text gets -1).
   */
  function layout(str, o) {
    const font = o.font || 'type';
    const g = font === 'type' ? GT : GD;
    const cap = font === 'type' ? 7 : 10;
    const k = o.size / cap;
    const seed = o.seed || 7;
    const hand = font === 'hand';
    const strokes = [];
    let pen = 0;
    const advFixed = 6.4;
    const glyphs = [];
    for (let ci = 0; ci < str.length; ci++) {
      const ch = str[ci];
      if (ch === ' ') {
        pen += font === 'type' ? advFixed : hand ? 3.3 + NB.rnd(seed, ci * 7) * 1.2 : 3.4;
        glyphs.push(null);
        continue;
      }
      const gl = g[ch] || g['?'];
      const wScale = hand ? 0.84 + NB.rnd(seed, ci * 13) * 0.24 : 1;
      const rise = hand ? NB.sr(seed, ci * 17) * 0.45 + Math.sin(ci * 0.7 + seed) * 0.35 : 0;
      const ox = pen;
      glyphs.push({ gl, ox, wScale, rise, ci });
      pen += font === 'type' ? advFixed : gl.w * wScale + (hand ? 1.5 + NB.rnd(seed, ci * 3) * 0.5 : 1.4) + (o.track || 0);
    }
    const totalW = (font === 'type' ? pen - 1.4 : pen - 1.4) * k;
    const alignOff = o.align === 'center' ? -totalW / 2 : o.align === 'right' ? -totalW : 0;
    const slant = o.slant !== undefined ? o.slant : hand ? 0.18 : 0;
    // write-on schedule
    let clock = o.t0 !== undefined ? o.t0 : -1;
    const perChar = o.cps ? 1 / o.cps : 0;
    glyphs.forEach((gg, gi) => {
      if (!gg) {
        if (clock >= 0) clock += perChar * (1.2 + NB.rnd(seed, gi * 5) * 1.4);
        return;
      }
      const n = gg.gl.strokes.length;
      gg.gl.strokes.forEach((s, si) => {
        const p = [];
        for (let i = 0; i < s.length; i += 2) {
          let x = s[i] * gg.wScale;
          let y = s[i + 1] + gg.rise;
          if (hand) {
            x += NB.sr(seed + gg.ci, si * 31 + i) * 0.32;
            y += NB.sr(seed + gg.ci, si * 37 + i + 1) * 0.32;
          }
          const px = (gg.ox + x) * k + (cap - y) * k * slant;
          p.push(o.x + alignOff + px, o.y + y * k);
        }
        let ts = -1;
        let te = -1;
        if (clock >= 0) {
          const share = (perChar * (0.75 + NB.rnd(seed, gg.ci * 19 + si) * 0.5)) / n;
          ts = clock;
          te = clock + share;
          clock = te;
        }
        strokes.push({ p, ts, te });
      });
    });
    return { strokes, w: totalW, end: clock };
  }

